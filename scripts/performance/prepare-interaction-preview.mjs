// Explicit app-source allowlist only. No env, tmp, credentials or fixture capabilities in uploads.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
const roots = ["src", "package.json", "package-lock.json", "next.config.ts", "tsconfig.json", "postcss.config.mjs", "vercel.json", ...(existsSync("public") ? ["public"] : [])];
const phase = process.argv[2] ?? "performance-stage3";
if (!/^[a-z0-9-]+$/.test(phase)) throw Error("INVALID_EVIDENCE_DIRECTORY");
const paths = [];
function add(path) { if (statSync(path).isDirectory()) for (const name of readdirSync(path)) add(`${path}/${name}`); else paths.push(path); }
for (const root of roots) add(root);
const digest = createHash("sha256");
for (const path of paths.sort().filter(path => path !== "src/lib/build-info.ts")) digest.update(path).update("\0").update(readFileSync(path)).update("\0");
const sourceDigest = digest.digest("hex"), buildId = `perf-20261022-${sourceDigest.slice(0, 16)}`;
writeFileSync("src/lib/build-info.ts", `// Generated by scripts/performance/prepare-interaction-preview.mjs from the deployed source manifest.\nexport const buildId = "${buildId}";\n`);
const files = paths.map(file => ({ file, data: readFileSync(file).toString("base64"), encoding: "base64" }));
mkdirSync(`tmp/${phase}`, { recursive: true });
mkdirSync(`docs/evidence/${phase}`, { recursive: true });
writeFileSync(`tmp/${phase}/deploy-files.json`, JSON.stringify(files));
writeFileSync(`docs/evidence/${phase}/source-manifest.json`, `${JSON.stringify({ buildId, sourceDigest, excludes: [".env*", "tmp", ".git", "docs", "next-env.d.ts (generated)", "test accounts/capabilities"], files: paths.map(path => ({ path, sha256: createHash("sha256").update(readFileSync(path)).digest("hex") })) }, null, 2)}\n`);
console.log(JSON.stringify({ buildId, files: files.length, bytes: JSON.stringify(files).length }));
